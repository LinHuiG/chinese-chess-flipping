import assert from 'node:assert/strict';
import {playerWake} from '../plugins/watch/player-wake.js';
const flush=()=>new Promise(resolve=>setImmediate(resolve));
const video=Object.assign(new EventTarget(),{paused:false,ended:false,currentSrc:'fixture.mp4'});
const doc=Object.assign(new EventTarget(),{hidden:false,defaultView:new EventTarget()});
let requests=0,releaseCount=0,defer,deny=false;
const locks=[],warnings=[];
const nav={wakeLock:{async request(type){assert.equal(type,'screen');requests++;if(defer)await defer;if(deny)throw Error('denied');const lock=new EventTarget();lock.release=async()=>{releaseCount++;lock.dispatchEvent(new Event('release'));};locks.push(lock);return lock;}}};
const wake=playerWake(video,message=>warnings.push(message),doc,nav);
video.dispatchEvent(new Event('playing'));await flush();assert.equal(requests,1);
doc.dispatchEvent(new Event('pointerdown'));await flush();assert.equal(requests,1,'Reuse active lock');
video.paused=true;video.dispatchEvent(new Event('pause'));await flush();assert.equal(releaseCount,1);
video.paused=false;video.dispatchEvent(new Event('playing'));await flush();assert.equal(requests,2);
doc.hidden=true;doc.dispatchEvent(new Event('visibilitychange'));await flush();assert.equal(releaseCount,2);
doc.hidden=false;doc.dispatchEvent(new Event('visibilitychange'));await flush();assert.equal(requests,3);
await locks.at(-1).release();await flush();assert.equal(requests,3,'OS release must not cause an automatic retry loop');
doc.dispatchEvent(new Event('pointerdown'));await flush();assert.equal(requests,4);
doc.defaultView.dispatchEvent(new Event('pagehide'));await flush();assert.equal(releaseCount,4);
doc.defaultView.dispatchEvent(new Event('pageshow'));await flush();assert.equal(requests,5);
video.paused=true;await wake.sync();
let resolve;defer=new Promise(r=>resolve=r);video.paused=false;const pending=wake.sync();
video.paused=true;await wake.sync();resolve();await pending;defer=null;
assert.equal(releaseCount,6,'A lock resolving after pause must be released');
deny=true;video.paused=false;await wake.sync();await wake.sync();assert.equal(warnings.length,1,'Denied requests warn once');
deny=false;await wake.sync();assert.equal(requests,9,'Can recover after rejection');
video.currentSrc='';video.dispatchEvent(new Event('emptied'));await flush();assert.equal(releaseCount,7);
assert.equal(warnings.length,1);
console.log('PASS wake lock: play/pause, visibility, OS release, page lifecycle, pending request race, rejection recovery and source removal');
